-- Step 2: learning_notes schema and sample-data migration
-- owner_id is intentionally a plain UUID column: no auth.users foreign key.
-- Use fictional training notes only during this stage.

CREATE TABLE IF NOT EXISTS public.learning_notes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id uuid,
    sample_marker text NOT NULL DEFAULT 'SAMPLE_NOTE_1',
    title text NOT NULL,
    content text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.learning_notes
    ADD COLUMN IF NOT EXISTS owner_id uuid;

ALTER TABLE public.learning_notes ENABLE ROW LEVEL SECURITY;

REVOKE ALL PRIVILEGES ON TABLE public.learning_notes FROM anon;
REVOKE ALL PRIVILEGES ON TABLE public.learning_notes FROM authenticated;
GRANT ALL PRIVILEGES ON TABLE public.learning_notes TO service_role;

-- Insert each fictional note only if its exact sample marker/title/content is absent.
INSERT INTO public.learning_notes (sample_marker, title, content)
SELECT 'SAMPLE_NOTE_1', v.title, v.content
FROM (VALUES
    ('과제', '실습용 가상 과제 기록'),
    ('포트폴리오', '실습용 가상 포트폴리오 기록'),
    ('아침 리추얼', '실습용 가상 리추얼 기록'),
    ('훈련 행정 자료', '실습용 가상 행정 기록')
) AS v(title, content)
WHERE NOT EXISTS (
    SELECT 1
    FROM public.learning_notes n
    WHERE n.sample_marker = 'SAMPLE_NOTE_1'
      AND n.title = v.title
      AND n.content = v.content
);
